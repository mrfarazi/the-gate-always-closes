"""make_tables.py -- regenerates every table of the paper from the result JSONs under results/.

Reads result JSONs (read-only) and writes
  results/tables/<name>.tex   one booktabs tabular per file (no table env / caption)
  results/NUMBERS.md       every number that appears in any table, with file + key path

Idempotent: every run overwrites the outputs. Optional sources (the four new knock-out files
j7_{hra_v1,small_alpha,raw_gated,no_dropout}_gqa.json) are included when present and skipped
cleanly when absent; the script prints which were found.

Conventions
  * accuracies: 1 decimal for n <= 2,000 items, 2 decimals for larger n; deltas signed, same precision
  * CIs as [lo, hi]
  * j5/j7 deltas + CIs are the ones stored in the JSON (paired bootstrap, 5,000 resamples,
    numpy default_rng(0), vs the value-0 arm); E1 (matched-mode) contrasts are recomputed here with
    scripts/analyze_iclr_e1.py's paired_bootstrap (10,000 resamples, RandomState(42) reset per contrast).

Usage:  python scripts/make_tables.py [--out DIR] [--check tests/golden/tables]
"""
