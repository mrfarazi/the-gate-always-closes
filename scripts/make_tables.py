# ----------------------------------------------------------------------------- registry
def relp(p):
    if p is None:
        return ""
    return os.path.relpath(p, R) if p.startswith(R) else p


class Registry:
    def __init__(self):
        self.sections = OrderedDict()
        self.found, self.missing, self.checks = [], [], []
        self.table_tokens = OrderedDict()  # table file -> (sources, sorted numeric tokens as printed)

    def add(self, section, label, value, src=None, key=""):
        self.sections.setdefault(section, []).append((label, str(value), relp(src), key))

    def note(self, section, text):
        self.sections.setdefault(section, []).append(("_note", text, "", ""))

    def check(self, what, got, expected, tol):
        ok = abs(float(got) - float(expected)) <= tol
        self.checks.append((what, got, expected, ok))
        return ok


REG = Registry()


# ----------------------------------------------------------------------------- helpers
def load(path, optional=False):
    if os.path.exists(path):
        REG.found.append(relp(path))
        with open(path) as f:
            return json.load(f)
    REG.missing.append(relp(path) + ("  (optional)" if optional else ""))
    return None


def dec(n):
    return 1 if n <= 2000 else 2


def facc(x, n):
    return f"{x:.{dec(n)}f}"


def fsg(x, n):
    return f"{x:+.{dec(n)}f}"


def fci(ci, n):
    return f"[{ci[0]:+.{dec(n)}f}, {ci[1]:+.{dec(n)}f}]"


def mdelta(d, ci, n):
    """math-mode 'delta [lo, hi]' cell"""
    return f"${fsg(d, n)}\\ {fci(ci, n)}$"


def mnum(x, nd=3, plus=True):
    s = f"{x:+.{nd}f}" if plus else f"{x:.{nd}f}"
    return f"${s}$"


def tex(s):
    return s.replace("_", "\\_")


def fint(n):
    return f"{n:,}"


def mint(n):
    """thousands separator safe inside math mode"""
    return f"{n:,}".replace(",", "{,}")


def write_tab(name, sources, note, body):
    path = os.path.join(TAB, name)
    with open(path, "w") as f:
        f.write(f"% {name} -- generated by scripts/make_tables.py "
                f"({datetime.date.today().isoformat()}); sources: {sources}\n")
        if note:
            for line in note.split("\n"):
                f.write(f"% {line}\n")
        f.write(body if body.endswith("\n") else body + "\n")
    import re as _re
    toks = set(m.group(1) for m in _re.finditer(r"(?<![\w.\-])(\d{1,3}(?:\{,\}\d{3})+(?:\.\d+)?|\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+\.\d+|\d+)(?![\w])", body))
    REG.table_tokens[name] = (sources, sorted(toks, key=lambda t: (len(t), t)))
    print("wrote", relp(path))


# ----------------------------------------------------------------------------- J5/J7 access
def val_of(row, d):
    vk = d.get("value_key", "gamma")
    for k in (vk, "gamma", "bias_mult", "scale", "value"):
        if k in row and row[k] is not None:
            return row[k]
    return None


def rows_of(d):
    """([(value,row)...] in JSON order, absent_row_or_None)"""
    rows, absent = [], None
    for r in d["rows"]:
        v = val_of(r, d)
        if r.get("label") == "prefix_absent" or v is None:
            absent = r
        else:
            rows.append((float(v), r))
    return rows, absent


def find_row(d, v):
    for val, r in rows_of(d)[0]:
        if math.isclose(val, v, rel_tol=1e-9, abs_tol=1e-12):
            return r
    return None


def value_index(d, v):
    for i, val in enumerate(d["values"]):
        if val is not None and math.isclose(float(val), v, rel_tol=1e-9, abs_tol=1e-12):
            return i
    return None


def flips_pct(d, v_off, v_on):
    """share of items whose prediction (GQA: string; SugarCrepe: chosen caption) differs."""
    pi = d.get("per_item")
    if not pi:
        return None
    i0, i1 = value_index(d, v_off), value_index(d, v_on)
    if i0 is None or i1 is None:
        return None
    if "pred" in pi:
        n = len(pi["pred"])
        k = sum(1 for p in pi["pred"] if p[i0] != p[i1])
    elif "s_pos" in pi and "s_neg" in pi:
        n = len(pi["s_pos"])
        k = sum(1 for sp, sn in zip(pi["s_pos"], pi["s_neg"])
                if (sp[i0] > sn[i0]) != (sp[i1] > sn[i1]))
    else:
        return None
    return 100.0 * k / n, k, n


def j7(ckpt, bench, optional=False):
    return load(os.path.join(JR, f"j7_{ckpt}_{bench}.json"), optional=optional)


def j5(name):
    return load(os.path.join(JR, f"j5_{name}.json"))


def gval(v):
    """compact gamma / scale label"""
    if v == 0:
        return "0"
    s = f"{v:g}"
    return s


