def tab_knockout_main():
    sec = "tab_knockout_main"
    designs = [
        ("hra_v1", "S1 attn.\\ bias ($\\alpha_{\\max}{=}0.05$)", "hra"),
        ("small_alpha", "S2 attn.\\ bias ($\\alpha_{\\max}{=}0.01$)", "hra"),
        ("stage2", "S3 margin loss, LoRA frozen", "hra"),
        ("no_dropout", "S4 gated prefix, no dropout", "prefix"),
        ("raw_gated", "S5 raw prefix, gated", "prefix"),
    ]
    benches = [("gqa_rel", "GQA-rel"), ("sugarcrepe", "SugarCrepe"), ("gqa", "GQA testdev")]
    lines = []
    lines.append("\\begin{tabular}{@{}llrrrrrr@{}}")
    lines.append("\\toprule")
    lines.append(" & & & \\multicolumn{2}{c}{pathway} & & & pathway \\\\")
    lines.append("\\cmidrule(lr){4-5}")
    lines.append("Design & learned gate & benchmark ($n$) & off & on & "
                 "$\\Delta$ on$-$off [95\\% CI] & flips \\% & absent \\\\")
    srcs = []
    for gi, (ck, name, kind) in enumerate(designs):
        lines.append("\\midrule")
        first = True
        for bench, bname in benches:
            d = j7(ck, bench, optional=(bench == "gqa"))
            if d is None:
                if bench == "gqa":
                    continue
                lines.append(f"{name if first else ''} & & {bname} & \\multicolumn{{5}}{{c}}{{file missing}} \\\\")
                first = False
                continue
            src = os.path.join(JR, f"j7_{ck}_{bench}.json")
            srcs.append(relp(src))
            n = d["n"]
            lg = d["learned_gate"]
            off = find_row(d, 0.0)
            if kind == "hra":
                on = find_row(d, 1.0)
                gate = f"$\\beta{{=}}{lg:+.3f}$"
                v_on = 1.0
                absent_s = "--"
            else:
                on = find_row(d, lg)
                gate = f"$\\tanh\\gamma{{=}}{lg:+.3f}$"
                v_on = lg
                absent = rows_of(d)[1]
                absent_s = facc(absent["acc"], n) if absent else "--"
            fl = flips_pct(d, 0.0, v_on)
            fl_s = f"{fl[0]:.1f}" if fl else "--"
            nlab = f"{bname} ({fint(n)})"
            if bench == "gqa":
                nlab = f"GQA testdev ({fint(n)})"
            lines.append(f"{name if first else ''} & {gate if first else ''} & {nlab} & "
                         f"{facc(off['acc'], n)} & {facc(on['acc'], n)} & "
                         f"{mdelta(on['delta_vs_0_pp'], on['ci95'], n)} & {fl_s} & {absent_s} \\\\")
            first = False
            # ---- register
            pre = f"{ck} / {bname} (n={n})"
            REG.add(sec, f"{pre}: learned gate", f"{lg:+.4f}", src, "learned_gate")
            REG.add(sec, f"{pre}: pathway off acc", facc(off["acc"], n), src,
                    f"rows[{d.get('value_key','gamma')}=0].acc")
            REG.add(sec, f"{pre}: pathway on acc", facc(on["acc"], n), src,
                    f"rows[{d.get('value_key','gamma')}={v_on:g}].acc")
            REG.add(sec, f"{pre}: delta on-off", fsg(on["delta_vs_0_pp"], n), src,
                    f"rows[..={v_on:g}].delta_vs_0_pp")
            REG.add(sec, f"{pre}: 95% CI", fci(on["ci95"], n), src, "rows[..].ci95 (paired bootstrap 5,000, seed 0)")
            if fl:
                REG.add(sec, f"{pre}: flips % (items whose prediction differs off vs on)",
                        f"{fl[0]:.1f} ({fl[1]}/{fl[2]})", src,
                        "per_item.pred[i][idx_off]!=per_item.pred[i][idx_on]" if "pred" in d["per_item"]
                        else "per_item: sign(s_pos-s_neg) differs between arms")
            if kind == "prefix" and absent:
                REG.add(sec, f"{pre}: prefix absent acc", facc(absent["acc"], n), src,
                        "rows[label=prefix_absent].acc")
                REG.add(sec, f"{pre}: absent - off", fsg(absent["delta_vs_0_pp"], n) + " " + fci(absent["ci95"], n),
                        src, "rows[label=prefix_absent].delta_vs_0_pp / ci95")
            if kind == "hra":
                uc = d.get("unit_check", {})
                for k in ("bias_abs_max_grid_boxes", "bias_abs_mean_grid_boxes", "bias_abs_max_zero_boxes_protocol"):
                    if k in uc:
                        REG.add(sec, f"{pre}: {k}", f"{uc[k]:.4g}", src, f"unit_check.{k}")
            if bench == "gqa":
                REG.add(sec, f"{pre}: item set", d.get("gqa_items", ""), src, "gqa_items / item_ids")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    REG.note(sec, "off = bias x0 (S1-S3) / gamma=0 with the 4 zero prefix slots kept (S4-S5); "
                  "on = bias x1 (learned beta) / gamma = learned tanh(gate); absent = prefix slots removed "
                  "(published LoRA-only condition; not applicable to the attention-bias designs). "
                  "All arms: 6x6 grid proposals, one wrapper (journal/scripts/j7_llava_knockout.py). "
                  "GQA-rel = first 1,000 relational testdev questions; SugarCrepe = first 1,000 pairs "
                  "(round-robin over 7 subtasks); GQA testdev (n=2,000) = first 2,000 testdev questions in file "
                  "order (item_ids checked); n=12,578 = full testdev.")
    write_tab("tab_knockout_main.tex", ", ".join(sorted(set(srcs))),
              "off = bias x0 / gamma=0 (zero slots kept); on = bias x1 / learned gamma; absent = prefix slots removed; "
              "6x6 grid proposals, single wrapper; Delta/CI = paired bootstrap (5,000) stored in the JSON",
              "\n".join(lines))


