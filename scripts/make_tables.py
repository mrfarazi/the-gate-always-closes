def check_against(golden_dir):
    """Compare regenerated tables with a golden set, ignoring '%' comment lines. Returns #diffs."""
    import glob
    ndiff = 0
    for gp in sorted(glob.glob(os.path.join(golden_dir, "*.tex"))):
        name = os.path.basename(gp)
        np_ = os.path.join(TAB, name)
        strip = lambda t: [ln for ln in t.split("\n") if not ln.startswith("%")]
        if not os.path.exists(np_):
            print(f"  MISSING {name}"); ndiff += 1; continue
        a, b = strip(open(gp).read()), strip(open(np_).read())
        if a != b:
            toks = lambda ls: re.findall(r"-?\d+(?:[.,]\d+)*", "\n".join(ls))
            same_nums = toks(a) == toks(b)
            print(f"  DIFF    {name}  (numeric tokens {'identical' if same_nums else 'DIFFER'})")
            ndiff += 0 if same_nums else 1
        else:
            print(f"  same    {name}")
    return ndiff


